package com.example.certextractor.utils

import com.example.certextractor.data.model.ExtractionField

object DynamicPromptBuilder {

    /**
     * بناء Prompt لاستخراج الحقول المحددة.
     *
     * يدعم:
     * - وثيقة واحدة.
     * - عدة صور.
     * - الجداول والكشوف متعددة الصفوف.
     *
     * المبدأ الأساسي:
     * الصف أولاً ← ثم الحقول داخل الصف.
     *
     * لا يتم استخراج الأعمدة بشكل مستقل ثم إعادة مطابقتها.
     */
    fun buildFieldsPrompt(
        fields: List<ExtractionField>
    ): String {

        val activeFields = fields.filter { it.enabled }

        if (activeFields.isEmpty()) {
            return buildNoFieldsPrompt()
        }

        /*
         * أسماء الحقول المطلوبة فقط.
         *
         * نعرضها للنموذج كـ "عقد إخراج".
         * أي حقل غير موجود هنا ممنوع إخراجه.
         */
        val fieldsDescription = activeFields.joinToString("\n") { field ->

            val description = field.description
                .trim()
                .ifBlank {
                    "اقرأ القيمة المرئية المرتبطة بهذا الحقل من نفس الصف."
                }

            "- \"${field.name}\": $description"
        }

        val jsonExample = activeFields.joinToString(",\n") { field ->
            "        \"${field.name}\": \"\""
        }

        val allowedKeys = activeFields.joinToString(", ") {
            "\"${it.name}\""
        }

        return """
أنت محرك OCR بصري متخصص في استخراج البيانات من الصور والجداول.

مهمتك الوحيدة:
قراءة البيانات المرئية في الصورة وإرجاع الحقول المطلوبة فقط.

الصورة هي مصدر الحقيقة الوحيد.

لا تستخدم:
- المعرفة الخارجية.
- الذاكرة.
- التخمين.
- التوقع.
- المعلومات من صور أخرى.
- معلومات من صف آخر.
- معلومات من عمود آخر كبديل.
- معرفة أسماء الأشخاص أو المؤسسات مسبقًا.

==================================================
الحقول المطلوبة — عقد الإخراج
==================================================

الحقول المطلوبة هي:

$fieldsDescription

مهم جدًا:

مفاتيح values المسموح بها هي فقط:

$allowedKeys

ممنوع إضافة أي مفتاح آخر داخل values.

إذا ظهر في الصورة حقل أو عمود آخر غير مطلوب:
تجاهله تمامًا.

مثال:

إذا كانت الصورة تحتوي على:

الاسم
المؤهل
التخصص
نوع الوظيفة
المدرسة
الراتب

وكان المطلوب فقط:

الاسم
المؤهل
التخصص

فأخرج فقط:

الاسم
المؤهل
التخصص

ولا تخرج:

نوع الوظيفة
المدرسة
الراتب

==================================================
قاعدة مهمة جدًا: لا تستبدل الحقول
==================================================

كل حقل مطلوب له معنى مستقل.

إذا كان المطلوب:

"المؤهل"

فإن قيمة "المؤهل" يجب أن تأتي من خانة/عمود المؤهل فقط.

لا تستخدم:

- نوع الوظيفة.
- الوظيفة.
- المدرسة.
- التخصص.
- القسم.
- المهنة.
- أي عمود مجاور.

إذا كان المطلوب:

"التخصص"

فإن قيمة "التخصص" يجب أن تأتي من خانة/عمود التخصص فقط.

لا تستخدم:

- المؤهل.
- المدرسة.
- الوظيفة.
- نوع الوظيفة.
- القسم.
- أي عمود مجاور.

إذا كان الحقل المطلوب غير موجود أو لا يمكن تحديده بشكل موثوق:
استخدم "".

ممنوع استخدام حقل آخر كبديل.

مثال:

إذا طلب التطبيق:

"المؤهل"

وكانت الصورة تحتوي:

المؤهل | نوع الوظيفة | المدرسة

فالنتيجة يجب أن تكون قيمة عمود "المؤهل".

ممنوع أخذ قيمة "نوع الوظيفة".

وممنوع أخذ قيمة "المدرسة".

==================================================
قاعدة الصف — الأهم
==================================================

إذا كانت الصورة تحتوي على جدول أو كشف أو قائمة متعددة الصفوف:

كل صف مرئي = سجل مستقل.

لا تفصل الأعمدة عن بعضها.

لا تستخرج جميع الأسماء أولًا ثم جميع الأرقام.

لا تستخرج جميع الأرقام ثم تحاول مطابقة الأسماء.

لا تعيد بناء الجدول بعد استخراج الأعمدة.

بدلًا من ذلك:

اقرأ صفًا واحدًا بالكامل.

حدد جميع الحقول المطلوبة لهذا الصف.

ثم انتقل إلى الصف التالي.

الترتيب:

الصف 1
→ الاسم في الصف 1
→ المؤهل في الصف 1
→ التخصص في الصف 1
→ الرقم في الصف 1
→ بقية الحقول المطلوبة في الصف 1

ثم:

الصف 2
→ الاسم في الصف 2
→ المؤهل في الصف 2
→ التخصص في الصف 2
→ الرقم في الصف 2
→ بقية الحقول المطلوبة في الصف 2

وهكذا حتى نهاية الجدول.

==================================================
محاذاة القيم داخل الصف
==================================================

كل قيمة يجب أن ترتبط بالصف الأفقي الذي ظهرت فيه.

إذا كان:

الصف 1:
أحمد | بكالوريوس | محاسبة | 1000

والصف 2:
محمد | دبلوم | إدارة | 2000

فالنتيجة:

السجل 1:
الاسم = أحمد
المؤهل = بكالوريوس
التخصص = محاسبة
الرقم = 1000

السجل 2:
الاسم = محمد
المؤهل = دبلوم
التخصص = إدارة
الرقم = 2000

ممنوع:

السجل 2:
الاسم = محمد
الرقم = 1000

لأن 1000 ظهر في صف أحمد.

==================================================
منع انزياح الأرقام
==================================================

الأرقام المالية والأرقام الرقمية يجب أن تبقى مرتبطة بالصف الذي ظهرت فيه.

إذا ظهر:

الصف 1 → 1000
الصف 2 → 1500
الصف 3 → 2000

فلا يجوز أن تصبح:

الصف 1 → 1000
الصف 2 → 2000
الصف 3 → ""

ولا يجوز:

الصف 1 → ""
الصف 2 → 1000
الصف 3 → 1500

لا تنقل الرقم إلى الصف المجاور.

لا تفترض أن الرقم التالي يخص الاسم التالي.

انظر إلى الموضع الأفقي للرقم داخل الصف.

إذا لم تستطع تحديد الصف الذي ينتمي إليه الرقم:
استخدم "" بدلًا من وضعه في صف آخر.

==================================================
منع الانزياح بين جميع الحقول
==================================================

نفس القاعدة تنطبق على:

- الأسماء.
- الأرقام.
- المؤهلات.
- التخصصات.
- التواريخ.
- المبالغ.
- الوظائف.
- أرقام الهواتف.
- أرقام الهوية.
- أي حقل مطلوب.

القيمة لا تنتقل من صف إلى صف.

إذا كان الصف N يحتوي على:

اسم N
رقم N
مؤهل N
تخصص N

فجميع هذه القيم تبقى في السجل N.

لا يجوز وضع:

رقم N في السجل N+1.

ولا:

مؤهل N في السجل N+1.

ولا:

تخصص N في السجل N-1.

==================================================
