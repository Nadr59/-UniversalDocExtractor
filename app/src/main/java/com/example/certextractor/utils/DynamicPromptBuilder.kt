==================================================

لكل سجل أخرج row_number.

row_number هو رقم الصف المرئي في الجدول، وليس رقم الشخص من داخل البيانات.

ابدأ من:

1

ثم:

2

ثم:

3

وهكذا.

لا تستخدم row_number كبديل عن أي حقل مطلوب.

مثال:

[
  {
    "row_number": 1,
    "image_index": 1,
    "values": {
${
        jsonExample
}
    }
  },
  {
    "row_number": 2,
    "image_index": 1,
    "values": {
${
        jsonExample
}
    }
  }
]

إذا كان الجدول يحتوي على 29 صفًا فعليًا:
يجب أن تكون row_number من 1 إلى 29.

إذا كان يحتوي على 30 صفًا:
يجب أن تكون من 1 إلى 30.

==================================================
عدد السجلات
==================================================

عدد عناصر results يجب أن يساوي عدد الصفوف الفعلية التي تحتوي على سجلات.

لا تضف سجلًا وهميًا.

لا تحذف سجلًا.

لا تكرر سجلًا.

لا تضف سجلًا فقط للوصول إلى رقم معين.

إذا كان هناك صف غير واضح:
أخرج سجلًا لهذا الصف مع القيم التي يمكن قراءتها.

إذا لم يمكن قراءة أي حقل في الصف:
أخرج السجل بقيم فارغة.

لا تستبدل الصف غير الواضح بالصف السابق.

ولا بالصف التالي.

==================================================
رؤوس الأعمدة
==================================================

إذا كانت الصورة تحتوي على عناوين أعمدة:

حدد عنوان كل عمود أولًا.

اربط كل حقل مطلوب بعموده الصحيح.

بعد تحديد الأعمدة:

اقرأ كل صف أفقيًا.

مثال:

| الاسم | المؤهل | التخصص | المدرسة |

إذا كان المطلوب:

الاسم
المؤهل
التخصص

فلا تستخدم عمود المدرسة.

حتى إذا كانت المدرسة مكتوبة بوضوح أكثر من التخصص.

وضوح النص لا يغيّر هوية الحقل.

==================================================
الحقول المتجاورة
==================================================

قد تكون الحقول المطلوبة بجانب حقول أخرى غير مطلوبة.

لا تخلط بينها.

مثال:

| الاسم | المؤهل | التخصص | نوع الوظيفة | المدرسة |

إذا كان المطلوب:

الاسم
المؤهل
التخصص

فإن:

الاسم ← من عمود الاسم
المؤهل ← من عمود المؤهل
التخصص ← من عمود التخصص

ولا يجوز:

المؤهل ← نوع الوظيفة

ولا:

التخصص ← المدرسة

حتى لو كانت هذه الأعمدة ملاصقة.

==================================================
إذا كان اسم الحقل غير واضح
==================================================

إذا لم تستطع تحديد العمود الذي يمثل الحقل المطلوب بثقة:

لا تستبدله بعمود آخر.

استخدم:

""

بدلًا من التخمين.

==================================================
الأسماء
==================================================

اقرأ أسماء الأشخاص بصريًا.

لا تبحث عن الاسم الصحيح.

لا تصحح الاسم اعتمادًا على المعرفة.

لا تستخدم اسمًا مشابهًا.

لا تستخدم اسم الصف السابق.

لا تستخدم اسم الصف التالي.

لا تنقل اسمًا من سجل آخر.

إذا كان الاسم:

سيناء جمعان سعيد الرباكي

فلا تحوله إلى اسم آخر لأن هناك اسمًا مشابهًا معروفًا.

اقرأ ما يظهر في الصورة.

إذا كان جزء واضحًا وجزء غير واضح:
احتفظ بالجزء الواضح.

إذا لم يمكن قراءة الاسم:
استخدم "".

==================================================
الأرقام
==================================================

اقرأ الرقم بصريًا من نفس الصف.

لا تخمن.

لا تكمل.

لا تضف أصفارًا.

لا تحذف أرقامًا واضحة.

لا تغير ترتيب الأرقام.

لا تنقل الرقم من صف إلى صف.

إذا كان الرقم غير واضح:
استخدم "".

==================================================
القيم المالية
==================================================

القيمة المالية يجب أن ترتبط بالصف نفسه.

لا تربط المبلغ بالاسم اعتمادًا على ترتيب النتائج فقط.

استخدم الموقع البصري للرقم داخل الجدول.

إذا كان:

الشخص 1 ← 5000

الشخص 2 ← 6000

الشخص 3 ← 7000

فلا يجوز:

الشخص 1 ← 5000
الشخص 2 ← 7000
الشخص 3 ← ""

ويجب عدم نقل:

