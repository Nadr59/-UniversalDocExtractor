package com.example.certextractor.utils

import com.example.certextractor.data.model.ExtractionField

object DynamicPromptBuilder {

    fun buildFieldsPrompt(
        fields: List<ExtractionField>
    ): String {

        val activeFields = fields.filter { it.enabled }

        if (activeFields.isEmpty()) {
            return buildNoFieldsPrompt()
        }

        val fieldsDescription = activeFields.joinToString("\n") { field ->
            val description = field.description
                .trim()
                .ifBlank { "اقرأ القيمة المرئية من نفس الصف." }
            "- \"${field.name}\": $description"
        }

        val jsonExample = activeFields.joinToString(",\n") { field ->
            "          \"${field.name}\": \"\""
        }

        val allowedKeys = activeFields.joinToString(", ") { "\"${it.name}\"" }

        return """
أنت محرك OCR بصري متخصص في استخراج البيانات من الصور والجداول.

==================================================
الحقول المطلوبة
==================================================

$fieldsDescription

المفاتيح المسموح بها داخل values هي فقط:

$allowedKeys

ممنوع إضافة أي مفتاح آخر داخل values مهما كان.

==================================================
قاعدة الصف — الأهم
==================================================

إذا كانت الصورة تحتوي على جدول أو كشف أو قائمة:

كل صف أفقي مرئي = سجل مستقل.

اقرأ الصف 1 كاملاً ← استخرج حقوله ← انتقل إلى الصف 2.

لا تستخرج عموداً كاملاً ثم تعيد المطابقة.

لا تنقل قيمة من صف إلى صف آخر.

==================================================
منع خلط الأعمدة
==================================================

كل حقل مطلوب له عمود محدد في الصورة.

اربط الحقل المطلوب بعموده الصحيح بناءً على عنوان العمود.

ممنوع استخدام عمود مجاور كبديل.

مثال:

إذا كان المطلوب "المؤهل" فالقيمة تأتي من عمود "المؤهل" فقط.

ليس من "نوع الوظيفة". ليس من "المدرسة". ليس من أي عمود آخر.

إذا لم تستطع تحديد العمود الصحيح بثقة: استخدم "".

==================================================
row_number
==================================================

لكل سجل قيمة row_number تمثل رقم الصف في الصورة.

ابدأ من 1 وزد بمقدار 1 لكل صف.

row_number ليس حقلاً من البيانات. هو معرف داخلي فقط.

==================================================
عدد السجلات
==================================================

عدد السجلات يساوي عدد الصفوف الفعلية في الصورة.

لا تضف سجلاً وهمياً.

لا تحذف سجلاً.

لا تكرر سجلاً.

إذا كانت الصورة تحتوي على 29 صفاً: أعد 29 سجلاً بالضبط.

==================================================
فحص ذاتي قبل الإخراج
==================================================

قبل إخراج JSON تحقق من:

1. عدد السجلات = عدد الصفوف الفعلية؟
2. كل row_number فريد ومتسلسل؟
3. كل قيمة مأخوذة من نفس الصف؟
4. لا توجد قيمة انتقلت من صف إلى آخر؟
5. كل حقل مأخوذ من عموده الصحيح؟
6. لا توجد مفاتيح إضافية داخل values؟

إذا وجدت خطأً: صحّحه قبل الإخراج.

==================================================
JSON — شكل الإخراج الوحيد المقبول
==================================================

أعد JSON فقط. لا Markdown. لا شرح. لا نص خارج JSON.

الشكل الوحيد المقبول:

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "values": {
$jsonExample
      }
    },
    {
      "row_number": 2,
      "image_index": 1,
      "values": {
$jsonExample
      }
    }
  ]
}

هذا هو الشكل الوحيد. لا تستخدم أي شكل آخر.

لا تعيد مصفوفة مباشرة بدون غلاف results.

لا تعيد كائناً مفرداً بدون results.

كل صف = عنصر مستقل داخل results.
        """.trimIndent()
    }

    fun buildFreeTextPrompt(
        userPrompt: String
    ): String {

        val cleanUserPrompt = userPrompt.trim()

        return """
أنت محرك OCR بصري لاستخراج المعلومات من الصور والوثائق.

طلب المستخدم:

$cleanUserPrompt

اقرأ المعلومات المطلوبة من الصورة فقط.

لا تخمن. لا تستخدم المعرفة الخارجية. لا تستخدم الذاكرة.

==================================================
الجداول
==================================================

إذا كانت الصورة تحتوي على جدول:

كل صف = سجل مستقل.

اقرأ الصف كاملاً قبل الانتقال إلى التالي.

لا تنقل قيمة من صف إلى صف آخر.

==================================================
JSON — شكل الإخراج الوحيد المقبول
==================================================

أعد JSON فقط. لا Markdown. لا شرح.

الشكل الوحيد المقبول:

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "data": {}
    }
  ]
}

إذا كانت الصورة تحتوي على عدة صفوف:

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "data": {}
    },
    {
      "row_number": 2,
      "image_index": 1,
      "data": {}
    }
  ]
}

لا تعيد مصفوفة مباشرة. استخدم غلاف results دائماً.
        """.trimIndent()
    }

    private fun buildNoFieldsPrompt(): String {

        return """
أنت محرك OCR بصري.

حلل الصور كما هي. اقرأ النص المرئي فقط.

لا تخمن. لا تستنتج. لا تستخدم المعرفة الخارجية.

إذا كانت الصورة تحتوي على جدول:

كل صف = سجل مستقل.

اقرأ الصف كاملاً قبل الانتقال إلى التالي.

لا تنقل القيم بين الصفوف.

أعد JSON فقط. الشكل الوحيد المقبول:

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "values": {}
    }
  ]
}

لا تعيد مصفوفة مباشرة. استخدم غلاف results دائماً.
        """.trimIndent()
    }
}
