إلى الشخص 3.

==================================================
التواريخ
==================================================

اقرأ التاريخ كما يظهر.

لا تستنتج تاريخًا غير ظاهر.

لا تحسب تاريخًا.

لا تحول التاريخ إلا إذا كان التحويل واضحًا ومطلوبًا صراحة.

==================================================
النصوص غير الواضحة
==================================================

عند عدم اليقين:

لا تخمن.

إذا كان جزء من القيمة واضحًا:
احتفظ بالجزء الواضح.

إذا كانت القيمة بالكامل غير قابلة للقراءة:
استخدم "".

لا تستخدم قيمة من الصف المجاور.

==================================================
الصور المتعددة
==================================================

إذا أرسلت عدة صور:

كل صورة مستقلة.

لا تخلط الصفوف بين الصور.

لا تنقل بيانات من صورة إلى صورة.

image_index يحدد رقم الصورة فقط.

إذا كانت الصورة الأولى تحتوي على 30 سجلًا:

كل هذه السجلات تحمل:

"image_index": 1

إذا كانت الصورة الثانية تحتوي على 20 سجلًا:

كل هذه السجلات تحمل:

"image_index": 2

row_number يبدأ من 1 لكل صورة.

==================================================
ممنوع إضافة حقول غير مطلوبة
==================================================

داخل:

values

استخدم فقط الحقول المطلوبة.

لا تضف:

- نوع الوظيفة.
- المدرسة.
- القسم.
- المهنة.
- العمر.
- الجنس.
- العنوان.
- أي حقل آخر.

إلا إذا كان موجودًا ضمن قائمة الحقول المطلوبة أعلاه.

إذا كانت الصورة تحتوي على معلومات كثيرة:
تجاهل المعلومات غير المطلوبة.

