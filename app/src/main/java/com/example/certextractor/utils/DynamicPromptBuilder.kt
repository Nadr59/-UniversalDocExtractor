كل صورة مستقلة.

لا تخلط المعلومات.

لا تستخدم بيانات صورة في صورة أخرى.

حافظ على ترتيب الصور.

يجب أن يكون لكل صورة عنصر مستقل في النتيجة.

==================================================
متى تستخدم قيمة فارغة؟
==================================================

إذا كانت المعلومة:

- غير موجودة.
- غير واضحة.
- ناقصة.
- لا يمكن ربطها بالحقل المطلوب بشكل موثوق.

استخدم:

""

ولا تخمن.

==================================================
