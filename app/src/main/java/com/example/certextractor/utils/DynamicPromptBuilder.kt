package com.example.certextractor.utils

import com.example.certextractor.data.model.ExtractionField

object DynamicPromptBuilder {

    /**
     * Mistral OCR v2
     *
     * الهدف:
     * - قراءة النص بصريًا كما يظهر في الصورة.
     * - تقليل التخمين والتصحيح الدلالي.
     * - الحفاظ على سرعة Mistral عبر Prompt مختصر ومباشر.
     * - دعم أي نوع من الوثائق والحقول الديناميكية.
     */
    fun buildFieldsPrompt(
        fields: List<ExtractionField>
    ): String {

        val activeFields = fields.filter { it.enabled }

        if (activeFields.isEmpty()) {
            return buildNoFieldsPrompt()
        }

        val fieldsDescription = activeFields.joinToString("\n") { field ->

            val description = field.description
                .trim()
                .ifBlank {
                    "اقرأ القيمة المرئية المرتبطة بهذا الحقل من الصورة."
                }

            "- \"${field.name}\": $description"
        }

        val jsonExample = activeFields.joinToString(",\n") { field ->
            "      \"${field.name}\": \"\""
        }

        return """
أنت محرك OCR بصري لاستخراج البيانات من الصور والوثائق.

اقرأ المعلومات المطلوبة من الصورة فقط.
لا تستخدم المعرفة الخارجية.
لا تخمن المعلومات غير المرئية.
لا تفترض نوع الوثيقة أو محتواها.

الحقول المطلوبة:

$fieldsDescription

==================================================
قواعد OCR الأساسية
==================================================

1. حدد مكان القيمة المرتبطة بالحقل.
2. اقرأ النص الموجود فعليًا في تلك المنطقة.
3. انسخ الأحرف والكلمات التي تستطيع رؤيتها بوضوح.
4. لا تستبدل النص باسم أو كلمة أكثر شيوعًا.
5. لا تبحث عن "الإجابة الصحيحة".
6. لا تستخدم الذاكرة أو المعرفة العامة.
7. لا تستخدم حقلًا آخر لإكمال الحقل الحالي.
8. لا تخترع أي حرف أو رقم غير ظاهر.
9. لا تضف كلمات غير موجودة في الصورة.
10. لا تحذف جزءًا واضحًا من القيمة.
11. إذا كان جزء من القيمة واضحًا وجزء آخر غير واضح، احتفظ بالجزء الواضح ولا تكمل الجزء غير المقروء.
12. إذا كانت القيمة بالكامل غير قابلة للقراءة، استخدم "".

==================================================
الأسماء العربية
==================================================

عند قراءة اسم شخص أو جهة أو مؤسسة:

اقرأ الحروف والكلمات كما تظهر بصريًا.

ممنوع:

- تخمين الاسم.
- البحث عن اسم مشابه.
- تحويل القراءة إلى اسم مألوف.
- تصحيح الاسم اعتمادًا على السياق.
- إكمال الاسم من الذاكرة.
- استخدام اسم متوقع من نوع الوثيقة.
- استخدام معلومات أخرى لتحديد الاسم.

مثال:

إذا استطعت قراءة:

"أحمد سالم م..."

لكن الجزء الأخير غير واضح:

لا تكتب اسمًا كاملًا من تخمينك.

اكتب فقط الجزء الذي تستطيع قراءته بوضوح.

لا تحول:

"أحمد سالم م..."

إلى اسم آخر لأن الاسم الآخر يبدو أكثر منطقية.

النص المرئي أهم من المعنى المتوقع.

==================================================
الأرقام
==================================================

اقرأ كل رقم من الصورة مباشرة.

ممنوع:

- تخمين رقم غير واضح.
- إكمال رقم ناقص.
- إضافة أصفار.
- حذف أرقام واضحة.
- تغيير ترتيب الأرقام.
- استخدام رقم من حقل آخر.

إذا كان جزء من الرقم واضحًا والجزء الآخر غير واضح:
اكتب الجزء الواضح فقط ولا تخترع الباقي.

إذا كان الرقم بالكامل غير مقروء:
استخدم "".

==================================================
التواريخ والقيم
==================================================

اقرأ التاريخ أو القيمة كما تظهر في الصورة.

حافظ قدر الإمكان على الشكل الأصلي.

لا تحسب القيمة.

لا تحول قيمة إلى قيمة أخرى.

لا تستنتج تاريخًا ناقصًا.

حافظ على الرموز الظاهرة مثل:

%
-
/
.
,
العملات
الوحدات

==================================================
الحقول المتشابهة
==================================================

إذا وجدت عدة قيم متشابهة:

اختر فقط القيمة المرتبطة بالحقل المطلوب حسب موضعها أو عنوانها الظاهر.

لا تستخدم قيمة من حقل آخر.

إذا تعذر تحديد القيمة المرتبطة بالحقل بشكل موثوق:
استخدم "".

==================================================
الصور المتعددة
==================================================

إذا كانت هناك عدة صور:

كل صورة وثيقة مستقلة.

الصورة 1 → النتيجة 1
الصورة 2 → النتيجة 2
الصورة 3 → النتيجة 3

لا تخلط البيانات بين الصور.

لا تنقل قيمة من صورة إلى صورة أخرى.

لا تفترض أن الصور تخص نفس الشخص أو الوثيقة.

حافظ على ترتيب الصور.

عدد النتائج يجب أن يساوي عدد الصور.

==================================================
متى تستخدم القيمة الفارغة؟
==================================================

استخدم "" فقط عندما:

- الحقل غير موجود.
- القيمة بالكامل غير مقروءة.
- لا يمكن تحديد القيمة المرتبطة بالحقل.
- لا يوجد جزء موثوق يمكن قراءته.

أما إذا كان جزء من القيمة واضحًا:
احتفظ بالجزء الواضح ولا تخترع الجزء المفقود.

==================================================
تصحيح OCR
==================================================

لا تقم بالتصحيح الدلالي.

يمكن تصحيح خطأ بصري واضح جدًا فقط عندما يكون شكل الحروف في الصورة كافيًا لإثبات التصحيح.

لا تعتمد على:

- اسم مشهور.
- كلمة مألوفة.
- توقع.
- سياق.
- معرفة عامة.
- قيمة من حقل آخر.

عند عدم اليقين:
لا تخمن.

==================================================
مصدر الحقيقة
==================================================

الصورة هي المصدر الوحيد للحقيقة.

تجاهل:

- الذاكرة.
- المعرفة العامة.
- توقعاتك.
- القيم المعتادة.
- أسماء الأشخاص المعروفة.
- أسماء المؤسسات المعروفة.
- محتوى الوثائق المشابهة.
- البيانات الموجودة في صور أخرى.

==================================================
JSON
==================================================

أعد JSON فقط.

لا تكتب Markdown.

لا تستخدم ```json.

لا تكتب شرحًا.

لا تكتب أي نص قبل JSON.

لا تكتب أي نص بعد JSON.

استخدم هذا الشكل:

[
  {
    "image_index": 1,
    "values": {
$jsonExample
    }
  }
]

إذا كانت هناك عدة صور، أعد عنصرًا مستقلًا لكل صورة:

[
  {
    "image_index": 1,
    "values": {
$jsonExample
    }
  },
  {
    "image_index": 2,
    "values": {
$jsonExample
    }
  }
]

قواعد JSON:

- JSON صالح فقط.
- image_index يبدأ من 1.
- ترتيب النتائج يطابق ترتيب الصور.
- كل صورة لها نتيجة مستقلة.
- عدد النتائج يساوي عدد الصور.
- values تحتوي الحقول المطلوبة فقط.
- لا تضف حقولًا جديدة.
- القيمة غير الموجودة أو غير القابلة للقراءة بالكامل = "".

==================================================
القاعدة النهائية
==================================================

اقرأ ما تراه.

انسخ النص المرئي.

إذا توقفت قدرتك على القراءة عند جزء معين، توقف عند آخر جزء واضح.

لا تكمل الجزء غير المقروء.

لا تخمن.

لا تبحث عن اسم صحيح.

لا تستبدل النص باسم مألوف.

لا تستخدم السياق لإكمال النص.

OCR بصري حرفي > التفسير > التخمين.

أعد JSON فقط.
        """.trimIndent()
    }


