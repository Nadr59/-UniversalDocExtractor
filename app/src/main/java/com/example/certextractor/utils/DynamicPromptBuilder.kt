اقرأ الحروف والكلمات كما تظهر بصريًا.

ممنوع:

- تخمين الاسم.
- البحث عن اسم مشابه.
- تحويل القراءة إلى اسم مألوف.
- تصحيح الاسم اعتمادًا على السياق.
- إكمال الاسم من الذاكرة.
