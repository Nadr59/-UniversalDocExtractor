2. اقرأ النص الموجود فعليًا في تلك المنطقة.
3. انسخ الأحرف والكلمات التي تستطيع رؤيتها بوضوح.
4. لا تستبدل النص باسم أو كلمة أكثر شيوعًا.
5. لا تبحث عن "الإجابة الصحيحة".
6. لا تستخدم الذاكرة أو المعرفة العامة.
7. لا تستخدم حقلًا آخر لإكمال الحقل الحالي.
8. لا تخترع أي حرف أو رقم غير ظاهر.
9. لا تضف كلمات غير موجودة في الصورة.
10. لا تحذف جزءًا واضحًا من القيمة.
11. إذا كان جزء من القيمة واضحًا وجزء آخر غير واضح، احتفظ بالجزء الواضح ولا تكمل الجزء غير المقروء.
