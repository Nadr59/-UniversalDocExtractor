==================================================

انسخ التاريخ والقيمة كما تظهر.

حافظ على الرموز والوحدات والنسب والعملات والصيغة الأصلية قدر الإمكان.

لا تحسب أو تستنتج قيمة.

==================================================
الصور المتعددة
