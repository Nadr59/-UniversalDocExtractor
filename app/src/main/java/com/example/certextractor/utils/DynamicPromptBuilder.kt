package com.example.certextractor.utils

import com.example.certextractor.data.model.ExtractionField

object DynamicPromptBuilder {

    /**
     * بناء Prompt لاستخراج الحقول المحددة.
     *
     * مهم:
     * قد يتم إرسال صورة واحدة أو عدة صور في نفس الطلب.
     * كل صورة تمثل وثيقة مستقلة تمامًا.
     */
    fun buildFieldsPrompt(
        fields: List<ExtractionField>
    ): String {

        val activeFields = fields.filter { it.enabled }

        if (activeFields.isEmpty()) {
            return buildNoFieldsPrompt()
        }

        val fieldsDescription = activeFields.joinToString("\n") { field ->

            val description = field.description
                .trim()
                .ifBlank {
                    "استخرج القيمة المتعلقة بهذا الحقل كما تظهر في الصورة."
                }

            "- \"${field.name}\": $description"
        }

        val jsonExample = activeFields.joinToString(",\n") { field ->
            "    \"${field.name}\": \"\""
        }

        return """
أنت نظام متخصص في قراءة الصور والوثائق واستخراج البيانات منها.

مهم جدًا:
قد يتم إرسال صورة واحدة أو عدة صور في نفس الطلب.

كل صورة تمثل وثيقة مستقلة تمامًا.

إذا تم إرسال عدة صور:
- تعامل مع كل صورة بشكل مستقل.
- لا تعتبر الصور صفحات لوثيقة واحدة.
- لا تخلط أي معلومة بين الصور.
- لا تستخدم معلومة من صورة للإجابة عن صورة أخرى.
- يجب أن تنتج نتيجة JSON مستقلة لكل صورة.
- يجب أن يكون ترتيب النتائج مطابقًا لترتيب الصور المرسلة.
- عدد النتائج يجب أن يساوي عدد الصور التي تم تحليلها.

==================================================
الحقول المطلوبة
==================================================

$fieldsDescription

==================================================
قواعد الاستخراج الصارمة
==================================================

1. استخرج المعلومات الموجودة فعليًا في الصورة فقط.

2. ممنوع التخمين.

3. ممنوع الاستنتاج عندما لا تكون المعلومة ظاهرة بوضوح.

4. ممنوع اختراع أي قيمة غير موجودة في الصورة.

5. إذا لم تجد الحقل في الصورة، اجعل قيمته:
""

6. إذا كان النص موجودًا ولكنه غير واضح أو غير مقروء، اجعل القيمة:
""
ولا تحاول تخمينها.

7. إذا كان جزء من الاسم غير واضح، لا تكمل الجزء الناقص من عندك.

8. إذا كان الرقم غير واضح، لا تخمن الأرقام الناقصة.

9. الأرقام مهمة جدًا:
انقلها كما تظهر في الصورة، ولا تستبدلها برقم آخر بناءً على الاحتمال.

10. لا تفترض السنة الدراسية أو التاريخ أو المعدل أو رقم القيد من سياق الوثيقة.

11. لا تفترض اسم المدرسة أو الجامعة أو المؤسسة إذا لم يكن ظاهرًا بوضوح.

12. لا تستخدم المعرفة العامة لإكمال المعلومات الناقصة.

13. لا تستخدم معلومات من صورة أخرى.

14. إذا ظهرت قيمة مشابهة في أكثر من مكان، اختر القيمة المرتبطة بالحقل المطلوب فقط.

15. حافظ على ترتيب وتسلسل الأرقام كما تظهر في الوثيقة.

16. حافظ على النص الأصلي قدر الإمكان.

17. لا تعيد صياغة الأسماء.

18. لا تترجم النصوص المستخرجة.

19. لا تغير لغة القيمة المستخرجة.

20. لا تضف كلمات غير موجودة في الوثيقة.

==================================================
تصحيح أخطاء OCR
==================================================

يمكنك تصحيح خطأ OCR فقط عندما يكون التصحيح واضحًا جدًا ومؤكدًا من الصورة نفسها.

مثال:
إذا كانت كلمة واضحة في الصورة وتمت قراءتها بحرف خاطئ بسبب OCR، يمكن تصحيحها.

لكن:

- لا تصحح الاسم بناءً على التخمين.
- لا تصحح رقمًا غير واضح.
- لا تخمن حرفًا مفقودًا.
- عند الشك، اترك القيمة فارغة.

الأولوية دائمًا هي:

الدقة وعدم الاختلاق > اكتمال البيانات.

==================================================
التعامل مع الصور المتعددة
==================================================

إذا أرسلت 5 صور مثلًا:

الصورة 1 ← نتيجة 1
الصورة 2 ← نتيجة 2
الصورة 3 ← نتيجة 3
الصورة 4 ← نتيجة 4
الصورة 5 ← نتيجة 5

يجب عدم دمج النتائج.

إذا كانت الصورة رقم 3 تحتوي على اسم مختلف عن الصورة رقم 1،
فلا تستخدم اسم الصورة رقم 1 في نتيجة الصورة رقم 3.

كل صورة مستقلة عن جميع الصور الأخرى.

==================================================
صيغة JSON المطلوبة
==================================================

إذا كانت هناك صورة واحدة فقط، أعد:

[
  {
    "image_index": 1,
    "values": {
$jsonExample
    }
  }
]

إذا كانت هناك عدة صور، أعد عنصرًا مستقلًا لكل صورة:

[
  {
    "image_index": 1,
    "values": {
$jsonExample
    }
  },
  {
    "image_index": 2,
    "values": {
$jsonExample
    }
  }
]

مهم جدًا:

- image_index يبدأ من 1.
- image_index يجب أن يطابق ترتيب الصورة.
- لا تضع معلومات إضافية خارج JSON.
- لا تستخدم Markdown.
- لا تستخدم ```json.
- لا تكتب أي شرح قبل JSON أو بعده.
- يجب أن يكون JSON صالحًا وقابلًا للتحليل مباشرة.

==================================================
قاعدة نهائية
==================================================

إذا كنت غير متأكد من قيمة معينة:

لا تخمنها.

أعدها فارغة:
""

لا تحاول جعل النتيجة تبدو مكتملة.

الدقة أهم من اكتمال البيانات.

أعد JSON فقط.
        """.trimIndent()
    }

    /**
     * بناء Prompt للاستخراج الحر.
     *
     * يستخدم عندما يحدد المستخدم بنفسه ما يريد استخراجه
     * بدل استخدام قائمة الحقول.
     */
    fun buildFreeTextPrompt(
        userPrompt: String
    ): String {

        val cleanUserPrompt = userPrompt.trim()

        return """
أنت نظام متخصص في قراءة الصور والوثائق واستخراج المعلومات منها.

==================================================
طلب المستخدم
==================================================

$cleanUserPrompt

==================================================
مهم جدًا: الصور المتعددة
==================================================

قد يتم إرسال صورة واحدة أو عدة صور في نفس الطلب.

كل صورة تمثل وثيقة مستقلة تمامًا.

إذا تم إرسال عدة صور:

- حلل كل صورة بشكل مستقل.
- لا تعتبر الصور صفحات لوثيقة واحدة.
- لا تخلط البيانات بين الصور.
- لا تستخدم معلومات صورة للإجابة عن صورة أخرى.
- أنشئ نتيجة مستقلة لكل صورة.
- حافظ على ترتيب الصور.
- يجب أن يساوي عدد النتائج عدد الصور.

==================================================
قواعد الاستخراج الصارمة
==================================================

1. استخرج المعلومات الموجودة فعليًا في الصورة فقط.

2. ممنوع التخمين.

3. ممنوع الاستنتاج غير المدعوم بما يظهر في الصورة.

4. ممنوع اختراع معلومات غير موجودة.

5. إذا كانت المعلومة غير موجودة، استخدم قيمة فارغة.

6. إذا كانت المعلومة موجودة ولكنها غير واضحة، استخدم قيمة فارغة بدل التخمين.

7. إذا كان الاسم غير واضح بالكامل أو جزئيًا، لا تكمله من عندك.

8. إذا كان الرقم غير واضح، لا تخمن الأرقام المفقودة.

9. لا تفترض التاريخ أو السنة أو المعدل أو رقم القيد.

10. لا تفترض اسم المؤسسة أو المدرسة أو الجامعة.

11. لا تستخدم المعرفة العامة لإكمال المعلومات الناقصة.

12. لا تستخدم بيانات من الصور الأخرى.

13. حافظ على النص كما يظهر في الوثيقة.

14. لا تترجم النص المستخرج.

15. لا تعيد صياغة الأسماء.

16. لا تضف كلمات غير موجودة في الوثيقة.

17. بالنسبة للأرقام، انقلها بدقة كما تظهر في الصورة.

18. إذا وجدت جدولًا، حافظ على العلاقة بين البيانات والصفوف والأعمدة.

19. إذا كان هناك أكثر من عنصر في الصورة، استخرج كل عنصر بشكل مستقل عند طلب المستخدم ذلك.

20. عند وجود شك، اترك القيمة فارغة بدل التخمين.

==================================================
تصحيح OCR
==================================================

يمكن تصحيح أخطاء OCR الواضحة جدًا فقط.

لا تقم بتصحيح:

- أسماء الأشخاص بناءً على التخمين.
- الأرقام غير الواضحة.
- التواريخ غير الواضحة.
- الكلمات الناقصة.
- المعلومات التي يمكن تفسيرها بأكثر من طريقة.

إذا لم تكن متأكدًا، اترك القيمة فارغة.

==================================================
صيغة النتيجة
==================================================

صورة واحدة:

[
  {
    "image_index": 1,
    "data": {}
  }
]

عدة صور:

[
  {
    "image_index": 1,
    "data": {}
  },
  {
    "image_index": 2,
    "data": {}
  }
]

==================================================
قواعد JSON
==================================================

- أعد JSON فقط.
- لا تكتب أي شرح خارج JSON.
- لا تستخدم Markdown.
- لا تستخدم ```json.
- لا تضف مقدمة أو خاتمة.
- يجب أن يكون JSON صالحًا.
- يجب أن يكون لكل صورة عنصر مستقل.
- يجب أن يكون ترتيب العناصر مطابقًا لترتيب الصور.
- يجب أن يساوي عدد العناصر عدد الصور.

==================================================
القاعدة الأهم
==================================================

لا تحاول تخمين ما لا تستطيع قراءته.

إذا لم تكن متأكدًا من قيمة:

استخدم:
""

الدقة وعدم الاختلاق أهم من ملء جميع الحقول.

أعد JSON فقط.
        """.trimIndent()
    }

    /**
     * في حال لم يتم تفعيل أي حقل.
     */
    private fun buildNoFieldsPrompt(): String {
        return """
أنت نظام متخصص في تحليل الصور والوثائق.

لم يتم تحديد حقول استخراج.

إذا تم إرسال صور، قم بتحليل كل صورة بشكل مستقل.

لا تخلط البيانات بين الصور.

لا تخمن أي معلومات.

أعد JSON فقط.

الصيغة:

[
  {
    "image_index": 1,
    "values": {}
  }
]

إذا كانت هناك عدة صور، أعد عنصرًا مستقلًا لكل صورة.

عدد النتائج يجب أن يساوي عدد الصور.

لا تكتب أي شرح خارج JSON.
        """.trimIndent()
    }
}
