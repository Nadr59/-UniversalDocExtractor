ما تغير عن v3 السابق؟

أهم تغيير هو هذه القاعدة:

قديمًا:

«إذا كنت غير متأكد من حرف → اترك القيمة فارغة.»

الآن:

«إذا كان جزء من القيمة واضحًا، احتفظ بالجزء الواضح وتوقف عند الجزء غير المقروء.»

وهذا مهم جدًا للأسماء العربية؛ لأننا نريد منع Mistral من تحويل:

"أحمد سالم م..."

إلى اسم كامل من عنده، لكن لا نريد أيضًا أن نخسر الجزء الذي استطاع قراءته فعلًا.

استبدل الملف الحالي بهذا الملف، ثم اختبر نفس الصورتين بالضبط بنفس الحقول. بهذه الطريقة ستكون المقارنة بين v3 وv2 عادلة، ونستطيع بعدها تحديد هل المشكلة ما زالت في الـPrompt أم أن قدرات OCR العربي في Mistral هي العامل المحدد.
