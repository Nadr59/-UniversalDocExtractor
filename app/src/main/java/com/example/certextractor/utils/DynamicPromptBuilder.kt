package com.example.certextractor.utils

import com.example.certextractor.data.model.ExtractionField

object DynamicPromptBuilder {

    fun buildFieldsPrompt(
        fields: List<ExtractionField>
    ): String {

        val activeFields = fields.filter { it.enabled }

        if (activeFields.isEmpty()) {
            return buildNoFieldsPrompt()
        }

        val fieldsDescription = activeFields.joinToString("\n") { field ->
            val description = field.description
                .trim()
                .ifBlank { "اقرأ القيمة من العمود الذي يحمل هذا الاسم فقط." }
            "- \"${field.name}\": $description"
        }

        val jsonExample = activeFields.joinToString(",\n") { field ->
            "          \"${field.name}\": \"\""
        }

        val allowedKeys = activeFields.joinToString(", ") { "\"${it.name}\"" }

        val fieldNamesList = activeFields.joinToString("\n") { "  - \"${it.name}\"" }

        return """
أنت محرك OCR بصري متخصص في استخراج البيانات من الجداول.

==================================================
الخطوة 1 — تحديد الأعمدة بالترتيب
==================================================

افحص صف العناوين في أعلى الجدول.

اقرأ اسم كل عمود بالترتيب من اليمين إلى اليسار.

سجّل رقم كل عمود واسمه داخلياً قبل قراءة أي بيانات.

==================================================
الخطوة 2 — تحديد أعمدة الحقول المطلوبة
==================================================

الحقول المطلوبة:

$fieldNamesList

لكل حقل مطلوب:

ابحث عن العمود الذي يحمل نفس الاسم بالضبط في صف العناوين.

سجّل رقم هذا العمود.

قاعدة صارمة جداً:

إذا وجدت العمود استخدم رقمه لقراءة البيانات.

إذا لم تجد العمود أو كان غير واضح اكتب "" ولا تستبدله بأي عمود آخر.

ممنوع منعاً باتاً:

استخدام عمود مجاور كبديل.

أخذ قيمة من عمود لم يُطلب.

تخطي عمود غير واضح والانتقال للتالي.

==================================================
الخطوة 3 — قراءة الصفوف
==================================================

بعد تحديد أرقام الأعمدة المطلوبة:

اقرأ كل صف أفقياً.

من كل صف استخرج فقط الخلايا الموجودة في أرقام الأعمدة المحددة.

تجاهل جميع الخلايا الأخرى في الصف.

==================================================
قاعدة العمود غير الواضح
==================================================

إذا كان نص خلية معينة غير واضح أو غير مقروء:

اكتب "" لهذا الحقل.

لا تنظر إلى الخلية المجاورة.

لا تأخذ قيمة من عمود آخر.

لا تخمن.

هذه القاعدة أهم من أي قاعدة أخرى.

==================================================
قاعدة المحاذاة الأفقية
==================================================

كل قيم السجل الواحد يجب أن تكون من نفس الصف الأفقي.

ممنوع نقل أي قيمة من صف إلى صف آخر.

==================================================
الحقول المطلوبة — عقد الإخراج
==================================================

$fieldsDescription

المفاتيح المسموح بها داخل values فقط:

$allowedKeys

ممنوع إضافة أي مفتاح آخر.

==================================================
عدد السجلات
==================================================

عدد السجلات = عدد الصفوف الفعلية في الجدول.

لا تضف سجلاً وهمياً.

لا تكرر سجلاً.

لا تحذف سجلاً.

==================================================
row_number
==================================================

لكل سجل أضف row_number يساوي رقم الصف في الجدول.

ابدأ من 1.

==================================================
فحص ذاتي قبل الإخراج
==================================================

1. هل كل حقل مأخوذ من العمود الصحيح بالاسم؟
2. هل أي عمود غير مطلوب تم تجاهله؟
3. هل الخلايا غير الواضحة أُعيدت كـ "" بدل استبدالها؟
4. هل كل قيم السجل من نفس الصف؟
5. هل عدد السجلات = عدد الصفوف الفعلية؟
6. هل row_number متسلسل بدون تكرار؟
7. هل values تحتوي فقط على المفاتيح المسموح بها؟

==================================================
JSON — الشكل الوحيد المقبول
==================================================

أعد JSON فقط. لا Markdown. لا شرح. لا نص خارج JSON.

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "values": {
$jsonExample
      }
    },
    {
      "row_number": 2,
      "image_index": 1,
      "values": {
$jsonExample
      }
    }
  ]
}

لا تعيد مصفوفة مباشرة. استخدم غلاف results دائماً.

كل صف = عنصر مستقل داخل results.
        """.trimIndent()
    }

    fun buildFreeTextPrompt(
        userPrompt: String
    ): String {

        val cleanUserPrompt = userPrompt.trim()

        return """
أنت محرك OCR بصري لاستخراج المعلومات من الصور والوثائق.

طلب المستخدم:

$cleanUserPrompt

اقرأ المعلومات المطلوبة من الصورة فقط.

لا تخمن. لا تستخدم المعرفة الخارجية. لا تستخدم الذاكرة.

==================================================
إذا كانت الصورة تحتوي على جدول
==================================================

الخطوة 1: حدد أعمدة الجدول من صف العناوين.

الخطوة 2: حدد الأعمدة المطلوبة بناءً على طلب المستخدم.

الخطوة 3: اقرأ كل صف أفقياً واستخرج القيم من الأعمدة المحددة فقط.

كل صف = سجل مستقل.

لا تنقل قيمة من صف إلى صف آخر.

==================================================
JSON — الشكل الوحيد المقبول
==================================================

أعد JSON فقط. لا Markdown. لا شرح.

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "data": {}
    }
  ]
}

لا تعيد مصفوفة مباشرة. استخدم غلاف results دائماً.
        """.trimIndent()
    }

    private fun buildNoFieldsPrompt(): String {

        return """
أنت محرك OCR بصري.

حلل الصورة كما هي. اقرأ النص المرئي فقط.

لا تخمن. لا تستنتج. لا تستخدم المعرفة الخارجية.

إذا كانت الصورة تحتوي على جدول:

الخطوة 1: حدد أعمدة الجدول من صف العناوين.
الخطوة 2: اقرأ كل صف أفقياً كوحدة واحدة.
الخطوة 3: لا تنقل القيم بين الصفوف.

أعد JSON فقط. الشكل الوحيد المقبول:

{
  "results": [
    {
      "row_number": 1,
      "image_index": 1,
      "values": {}
    }
  ]
}

لا تعيد مصفوفة مباشرة. استخدم غلاف results دائماً.
        """.trimIndent()
    }
}
