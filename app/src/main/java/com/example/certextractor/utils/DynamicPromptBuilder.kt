==================================================

إذا كانت الصورة تحتوي على جدول أو كشف أو قائمة تضم عدة أشخاص أو سجلات:

اعتبر كل صف سجلًا مستقلًا.

كل صف يجب أن يحتفظ بعلاقة جميع الحقول الموجودة في نفس الصف.

مثال:

الصف 1:
اسم 1 + رقم 1 + مؤهل 1

الصف 2:
اسم 2 + رقم 2 + مؤهل 2

الصف 3:
اسم 3 + رقم 3 + مؤهل 3

يجب أن تبقى بيانات كل صف مع بعضها.

ممنوع:

- فصل الأسماء عن الأرقام ثم إعادة مطابقتها لاحقًا.
- فصل الأعمدة ثم إعادة تركيب الصفوف.
- نقل قيمة من صف إلى صف آخر.
- إزاحة البيانات بين الصفوف.
- تكرار اسم الصف السابق.
- تكرار اسم الصف التالي.
- استخدام بيانات شخص آخر لتعويض قيمة غير واضحة.

اقرأ الجدول صفًا صفًا.

كل صف = سجل واحد.

