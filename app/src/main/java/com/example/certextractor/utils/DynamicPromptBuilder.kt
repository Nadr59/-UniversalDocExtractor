أعد JSON فقط.

صورة واحدة:

[
  {
    "image_index": 1,
    "values": {}
  }
]

عدة صور:

[
  {
    "image_index": 1,
    "values": {}
  },
  {
    "image_index": 2,
    "values": {}
  }
]

عدد النتائج يجب أن يساوي عدد الصور.

لا تكتب أي شرح خارج JSON.
        """.trimIndent()
    }
